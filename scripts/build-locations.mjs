/**
 * Build `scripts/source-data/facility-locations.json` from the raw survey
 * export — each facility's surveyed position and its rural/urban setting.
 *
 *     npm run data:locations
 *     npm run data:locations -- --local <path>
 *
 * The export, `ERA dataset_v4 (1).xlsx`, is 37 MB and not committed, and until
 * now `data:ingest` read it directly — so only a machine holding a copy could
 * rebuild the dashboard's data, and the scheduled sync could not run at all.
 * This takes out the five fields the dashboard uses (UUID, the state/LGA/name
 * key the ingest falls back to, setting, latitude and longitude) and commits
 * them, as `data:maturity` and `data:coverage` do for their workbooks.
 * `data:ingest` reads this file and never the export.
 *
 * Positions change only when facilities are resurveyed, so this runs by hand,
 * when a new export arrives — the daily sync does not need it. Every check the
 * ingest made on the export is made here instead (`parseFacilityWorkbook`:
 * the header found and asserted, coordinates inside Nigeria, rural or urban),
 * and the file is written in a fixed order, so an unchanged export writes no
 * diff.
 *
 * Coordinates are already published: the Assessed States maps plot every
 * facility from `public/data/`, so committing them here exposes nothing new.
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseFacilityWorkbook } from './facility-workbook.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const EXPORT = resolve(ROOT, 'ERA dataset_v4 (1).xlsx');
const OUT = resolve(ROOT, 'scripts/source-data/facility-locations.json');

const argv = process.argv.slice(2);
const local = argv.indexOf('--local');
const path = local === -1 ? EXPORT : resolve(argv[local + 1] ?? '');

if (!existsSync(path)) {
  process.stderr.write(
    `Missing ${path}.\n\nThe raw survey export is not in the repository (37 MB). Put a copy ` +
      `at that path, or pass --local <path>. You only need it when facilities are ` +
      `resurveyed: the committed ${OUT.slice(ROOT.length + 1)} is what the build reads.\n`,
  );
  process.exit(1);
}

const records = parseFacilityWorkbook(readFileSync(path))
  .map(({ uuid, nameKey, geography, lat, lon }) => ({ uuid, nameKey, geography, lat, lon }))
  .sort((a, b) => a.nameKey.localeCompare(b.nameKey) || String(a.uuid).localeCompare(String(b.uuid)));

const placed = records.filter((r) => r.lat !== null).length;
const header = {
  source: 'ERA dataset_v4 (1).xlsx',
  sheet: 'Raw data with readiness level',
  note:
    'Generated by scripts/build-locations.mjs — do not edit. One row per survey row: ' +
    'the UUID as written (two are numbers, not UUIDs, from spreadsheet auto-formatting), ' +
    'the state/LGA/name key the ingest falls back to for those, the rural/urban setting, ' +
    'and the surveyed position, or nulls where the GPS did not record.',
};
// One facility to a line: small, and a resurvey diffs as the rows it moved.
const head = JSON.stringify(header, null, 2).replace(/\n}$/, '');
writeFileSync(
  OUT,
  `${head},\n  "facilities": [\n${records.map((r) => `    ${JSON.stringify(r)}`).join(',\n')}\n  ]\n}\n`,
);
process.stderr.write(
  `Wrote ${records.length} facilities, ${placed} with a position, to ` +
    `${OUT.slice(ROOT.length + 1)}\n`,
);
